import esbuild from "esbuild";
import process from "process";
import { builtinModules } from 'node:module';
import { copyFileSync, writeFileSync, existsSync, mkdirSync, watch } from "fs";
import { join } from "path";
import { execSync, spawn } from "child_process";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");
const PLUGIN_ID = "true-recall";
const VAULT_PATH = process.env.VAULT;


const projectOutfile = "main.js";
const vaultPluginDir = VAULT_PATH
	? join(VAULT_PATH, ".obsidian", "plugins", PLUGIN_ID)
	: null;

if (vaultPluginDir && !existsSync(vaultPluginDir)) {
	mkdirSync(vaultPluginDir, { recursive: true });
}

function buildCSS() {
	try {
		const minifyFlag = prod ? ' --minify' : '';
		execSync(`npx @tailwindcss/cli -i src/shared/ui/styles.css -o styles.css${minifyFlag}`, { stdio: 'pipe' });
		console.log("✓ CSS built with Tailwind CLI" + (prod ? " (minified)" : ""));
	} catch (err) {
		console.error("CSS build failed:", err.message);
		throw err;
	}
}

function copyToVault() {
	if (!vaultPluginDir) return;

	try {
		copyFileSync(projectOutfile, join(vaultPluginDir, "main.js"));

		if (existsSync("manifest.json")) {
			copyFileSync("manifest.json", join(vaultPluginDir, "manifest.json"));
		}
		if (existsSync("styles.css")) {
			copyFileSync("styles.css", join(vaultPluginDir, "styles.css"));
		}

		const sqljsWasm = "node_modules/sql.js/dist/sql-wasm.wasm";
		if (existsSync(sqljsWasm)) {
			copyFileSync(sqljsWasm, join(vaultPluginDir, "sql-wasm.wasm"));
			console.log("✓ Copied sql-wasm.wasm");
		}


		if (!prod) {
			writeFileSync(join(vaultPluginDir, ".hotreload"), "");
		}

		console.log(`✓ Copied to vault: ${vaultPluginDir}`);
	} catch (err) {
		console.error("Failed to copy to vault:", err.message);
	}
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	define: {
		'process.env.SUPABASE_URL': JSON.stringify(process.env.SUPABASE_URL || ''),
		'process.env.SUPABASE_ANON_KEY': JSON.stringify(process.env.SUPABASE_ANON_KEY || ''),
		'process.env.POWERSYNC_URL': JSON.stringify(process.env.POWERSYNC_URL || ''),
	},
	loader: {
		'.wasm': 'binary',
	},
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	jsx: 'automatic',
	jsxImportSource: 'preact',
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: projectOutfile,
	minify: prod,
	plugins: [{
		name: "copy-to-vault",
		setup(build) {
			build.onStart(() => {
				buildCSS(); 
			});
			build.onEnd(() => {
				copyToVault();
			});
		}
	}],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();

	// Watch CSS separately — esbuild doesn't track non-bundled files
	const cssWatcher = spawn(
		"npx",
		["@tailwindcss/cli", "-i", "src/shared/ui/styles.css", "-o", "styles.css", "--watch"],
		{ stdio: "inherit" }
	);
	cssWatcher.on("error", (err) => console.error("CSS watcher error:", err.message));

	// Copy styles.css to vault whenever Tailwind rebuilds it
	if (vaultPluginDir) {
		watch("styles.css", () => {
			try {
				copyFileSync("styles.css", join(vaultPluginDir, "styles.css"));
			} catch {
				// File may not exist yet on first watch event
			}
		});
	}

	const cleanup = () => { cssWatcher.kill(); process.exit(0); };
	process.on("SIGINT", cleanup);
	process.on("SIGTERM", cleanup);
}
